import { test as perfTest } from '../../framework/fixtures/playwright';
import { AppiumAssertions } from '../../framework';
import TabBarComponent from '../../page-objects/wallet/TabBarComponent';
import SocialV1View from '../../page-objects/Social/SocialV1View';
import SocialProfileOnboardingView from '../../page-objects/Social/SocialProfileOnboardingView';
import TimerHelper from '../../framework/TimerHelper';
import { getPasswordForScenario } from '../../framework/utils/TestConstants.js';
import OnboardingView from '../../page-objects/Onboarding/OnboardingView';
import MetaMetricsOptInView from '../../page-objects/Onboarding/MetaMetricsOptInView';
import { createFreshSrpWallet } from '../onboarding/helpers/createFreshSrpWallet';
import {
  closePredictModal,
  dismissOnboardingInterestQuestionnaire,
  dismissPushNotificationExistingUserSheet,
} from '../../flows/wallet.flow';
import { enableHermesAppProfiling } from '../helpers/appProfiling';
import {
  Performance,
  PerformanceOnboarding,
  System,
} from '../../tags.performance.js';

/**
 * Create-new-wallet onboarding, then Social profile onboarding, against the
 * main-dev-without-srp APK. That build points at the dev API cluster and does
 * not bake a wallet, so the app opens on the onboarding screen. The production
 * onboarding suite does not discover this folder.
 */
perfTest.describe(`${Performance} ${System} ${PerformanceOnboarding}`, () => {
  perfTest(
    'Create a new wallet and onboard into Social on the dev build',
    { tag: '@metamask-onboarding-team' },
    async ({ currentDeviceDetails, performanceTracker }) => {
      perfTest.setTimeout(10 * 60 * 1_000);

      await AppiumAssertions.expectElementToBeVisible(
        OnboardingView.newWalletButton,
        {
          timeout: 60_000,
          description: 'Fresh-install onboarding screen should be ready',
        },
      );

      await enableHermesAppProfiling();

      const password = getPasswordForScenario('onboarding');
      if (!password) {
        throw new Error(
          'The onboarding password is required for the dev onboarding performance test.',
        );
      }
      await createFreshSrpWallet(password);

      // Optional post-onboarding prompts (setup, not timed).
      await MetaMetricsOptInView.tapIAgreeButton();
      await dismissOnboardingInterestQuestionnaire();
      await dismissPushNotificationExistingUserSheet();
      await closePredictModal();
      await AppiumAssertions.expectElementToBeVisible(
        TabBarComponent.tabBarWalletButton,
        { description: 'Wallet home should be visible' },
      );

      // Wallet creation above is setup. Only the Social profile onboarding is
      // timed. Connect X is skipped because it needs an external X login.
      const socialIntroTimer = new TimerHelper(
        'Time since the user taps Post on the Social home until the profile onboarding intro is visible',
        // Dev-build runs landed between 1.4s and 2.7s.
        { ios: 2_000, android: 3_000 },
        currentDeviceDetails.platform,
      );
      const socialProfileCreatedTimer = new TimerHelper(
        'Time since the ready step is visible until the profile is created and "Let\'s go" is enabled',
        // Social API. Dev-build runs landed around 1.7s.
        { ios: 2_500, android: 3_000 },
        currentDeviceDetails.platform,
      );
      const socialFinishTimer = new TimerHelper(
        'Time since the user taps "Let\'s go" until the Trending tab is visible',
        // Dev-build run landed at 2.0s.
        { ios: 2_000, android: 2_500 },
        currentDeviceDetails.platform,
      );

      await TabBarComponent.tapSocial();
      await AppiumAssertions.expectElementToBeVisible(SocialV1View.plusButton, {
        description: 'Social home should be ready',
      });

      await SocialV1View.tapPlusButton();
      await socialIntroTimer.measure(async () => {
        await AppiumAssertions.expectElementToBeVisible(
          SocialProfileOnboardingView.intro,
          { description: 'Profile onboarding intro should be visible' },
        );
      });

      await SocialProfileOnboardingView.tapCreateManuallyButton();
      await AppiumAssertions.expectElementToBeVisible(
        SocialProfileOnboardingView.usernameStep,
        { description: 'Username step should be visible' },
      );

      // The username is generated by the app, so Continue needs no typing.
      await SocialProfileOnboardingView.tapContinueButton();
      await AppiumAssertions.expectElementToBeVisible(
        SocialProfileOnboardingView.avatarStep,
        { description: 'Avatar step should be visible' },
      );

      await SocialProfileOnboardingView.tapContinueButton();
      await AppiumAssertions.expectElementToBeVisible(
        SocialProfileOnboardingView.accountStep,
        { description: 'Account step should be visible' },
      );

      await SocialProfileOnboardingView.tapContinueButton();
      await AppiumAssertions.expectElementToBeVisible(
        SocialProfileOnboardingView.readyStep,
        { description: 'Ready step should be visible' },
      );

      await socialProfileCreatedTimer.measure(async () => {
        await AppiumAssertions.expectElementToBeInteractive(
          SocialProfileOnboardingView.letsGoButton,
          {
            timeout: 30_000,
            description: 'Lets go should be enabled once the profile exists',
          },
        );
      });

      await SocialProfileOnboardingView.tapLetsGoButton();
      await socialFinishTimer.measure(async () => {
        await AppiumAssertions.expectElementToBeVisible(
          SocialV1View.trendingTab,
          {
            description: 'Trending tab should be visible',
          },
        );
      });

      performanceTracker.addTimers(
        socialIntroTimer,
        socialProfileCreatedTimer,
        socialFinishTimer,
      );
    },
  );
});
